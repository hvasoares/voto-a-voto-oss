/**
 * `make releases` writes `docs/releases.md`, the release map (#129): one row per git tag, with the commit the tag points at
 * (`git rev-list -n1`, the peeled commit of an annotated tag), its date, and the hand-written columns kept in `docs/releases-notes.json`
 * (tag -> milestone, rollback, known issues, and the deploy run found once with `gh` and stored, so the map does not depend on
 * GitHub history that expires). `make releases-check` (also a vitest file, so `npm test` runs it) fails when a tag has no row, a row's commit
 * is not where the tag points, or a row's tag is gone. The output is a pure function of tags and notes: a second run changes no byte.
 */
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

export interface Row {
  tag: string
  /** First seven characters of the commit the tag points at. */
  commit: string
  /** Commit date, YYYY-MM-DD. */
  date: string
}

export interface Note {
  milestone: string
  rollback: string
  known_issues: string
  /** Id of the successful deploy-pages run; null when none is known (written as n/a). */
  deploy_run?: number | null
  /** Short sha that the run built, when it is a later commit than the tag's own (the tag's own run was cancelled). */
  deploy_sha?: string | null
}

const ROOT = resolve(import.meta.dirname, '..', '..')
export const DEPLOY_REPO = 'hvasoares/voto-a-voto-oss'
export const LIVE_URL = 'https://voto-a-voto.com/'
const MAP = resolve(ROOT, 'docs', 'releases.md')
const NOTES = resolve(ROOT, 'docs', 'releases-notes.json')

const parts = (tag: string): number[] => tag.replace(/^v/, '').split('.').map(Number)
/** Version order; the pre-numbering `v1.0.0` sorts with the numbered ones, so it comes first. */
export const tagOrder = (a: string, b: string): number => {
  const [x, y] = [parts(a), parts(b)]
  for (let i = 0; i < Math.max(x.length, y.length); i++) if ((x[i] ?? 0) !== (y[i] ?? 0)) return (x[i] ?? 0) - (y[i] ?? 0)
  return 0
}

const cell = (s: string): string => s.replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim()
const run = (n: Note): string => {
  if (!n.deploy_run) return 'n/a'
  const link = `[${n.deploy_run}](https://github.com/${DEPLOY_REPO}/actions/runs/${n.deploy_run})`
  return n.deploy_sha ? `${link} (via \`${n.deploy_sha}\`)` : link
}

export function renderReleases(rows: Row[], notes: Record<string, Note>): string {
  const head = [
    '# Release map',
    '',
    `Generated by \`make releases\` from the git tags and \`docs/releases-notes.json\`; do not edit the table by hand (edit the notes file and run it again). \`make releases-check\` fails when a tag has no row or a row's commit is not where the tag points. The live site is ${LIVE_URL} and always shows the latest deploy.`,
    '',
    'Release step: after the suites pass and the tag is placed, run `make releases`, add any new notes for the tag, and commit the map. A pushed tag is never moved.',
    '',
    'The commit is the one the tag points at. The deploy run is the successful `deploy-pages` run of that commit; "via" names the later commit whose run published it, when the commit\'s own run was cancelled. `n/a` means no run is known.',
    '',
    '| Tag | Milestone | Commit | Date | Deploy run | Rollback | Known issues |',
    '| --- | --- | --- | --- | --- | --- | --- |',
  ]
  const body = [...rows].sort((a, b) => tagOrder(a.tag, b.tag)).map((r) => {
    const n = notes[r.tag] ?? { milestone: 'n/a', rollback: 'n/a', known_issues: 'n/a' }
    return `| \`${r.tag}\` | ${cell(n.milestone)} | \`${r.commit}\` | ${r.date} | ${run(n)} | ${cell(n.rollback)} | ${cell(n.known_issues)} |`
  })
  return [...head, ...body, ''].join('\n')
}

export function parseRows(md: string): { tag: string; commit: string }[] {
  return [...md.matchAll(/^\| `([^`]+)` \|.*?\| `([0-9a-f]{7,40})` \|/gm)].map((m) => ({ tag: m[1]!, commit: m[2]! }))
}

/**
 * Tags that live in two histories: `v1.0.0` points at a different commit in the original history (the private backup) and in
 * the rewritten one (the public repository), so a checkout of either is right. For these the row must exist, but the commit is
 * not compared.
 */
const TWO_HISTORY_TAGS = new Set(['v1.0.0'])

export function releaseProblems(md: string, tags: { tag: string; commit: string }[]): string[] {
  const rows = parseRows(md)
  const problems: string[] = []
  for (const t of tags) {
    const row = rows.find((r) => r.tag === t.tag)
    if (!row) problems.push(`${t.tag} has no row in docs/releases.md; run \`make releases\``)
    else if (!TWO_HISTORY_TAGS.has(t.tag) && !t.commit.startsWith(row.commit) && !row.commit.startsWith(t.commit)) problems.push(`${t.tag} points at ${t.commit} but the map says ${row.commit}; run \`make releases\``)
  }
  for (const r of rows) if (!tags.some((t) => t.tag === r.tag)) problems.push(`${r.tag} is in the map but is not a tag`)
  return problems
}

const git = (...args: string[]): string => execFileSync('git', args, { cwd: ROOT, encoding: 'utf8' }).trim()

export function readTags(): Row[] {
  const names = git('for-each-ref', '--format=%(refname:short)', 'refs/tags').split('\n').filter(Boolean)
  return names.map((tag) => {
    const full = git('rev-list', '-n1', tag)
    return { tag, commit: full.slice(0, 7), date: git('log', '-1', '--format=%cs', full) }
  })
}

/** Looks up, once, the successful deploy-pages run of each commit that has no stored one. Without `gh` or a network, nothing is filled. */
function fillDeployRuns(rows: Row[], notes: Record<string, Note>): boolean {
  const missing = rows.filter((r) => notes[r.tag] && notes[r.tag]!.deploy_run === undefined)
  if (missing.length === 0) return false
  let runs: { databaseId: number; headSha: string; conclusion: string }[]
  try {
    const out = execFileSync('gh', ['run', 'list', '-R', DEPLOY_REPO, '--workflow', 'deploy-pages', '--limit', '200', '--json', 'databaseId,headSha,conclusion'], { encoding: 'utf8' })
    runs = JSON.parse(out)
  } catch {
    return false
  }
  for (const r of missing) notes[r.tag]!.deploy_run = runs.find((x) => x.conclusion === 'success' && x.headSha.startsWith(r.commit))?.databaseId ?? null
  return true
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const rows = readTags()
  if (process.argv.includes('--check')) {
    if (rows.length === 0) {
      console.log('releases-check SKIPPED: this checkout has no tags (git fetch --tags)')
      process.exit(0)
    }
    const problems = releaseProblems(readFileSync(MAP, 'utf8'), rows)
    if (problems.length > 0) {
      console.error(`releases-check FAILED: ${problems.length} problem(s)`)
      for (const p of problems) console.error(`  - ${p}`)
      process.exit(1)
    }
    console.log(`releases-check: ${rows.length} tags, each with a row at the commit it points at.`)
  } else {
    const notes = JSON.parse(readFileSync(NOTES, 'utf8')) as Record<string, Note>
    if (fillDeployRuns(rows, notes)) writeFileSync(NOTES, JSON.stringify(notes, null, 2) + '\n')
    for (const r of rows) if (!notes[r.tag]) console.warn(`releases: ${r.tag} has no entry in docs/releases-notes.json (written as n/a); add its milestone, rollback and known issues`)
    const md = renderReleases(rows, notes)
    writeFileSync(MAP, md)
    console.log(`releases: ${rows.length} rows written to docs/releases.md`)
  }
}
